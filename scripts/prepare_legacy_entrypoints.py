"""Prepare ignored checkout-local entrypoints for an existing installation.

This explicit migration does not inspect private state or Codex settings, stop
processes, connect hosts, start a broker, or submit tasks. Dry-run is the default.
An unknown existing target aborts the entire preflight without overwriting it.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

MARKER = "Generated by AgentCaptain legacy-entrypoint migration."


def compatibility_files(root: Path) -> dict[str, bytes]:
    source = root / "src" / "agent_captain"
    required = [root / "scripts" / "captain.py", root / "terminal" / "terminal_broker.cjs",
                source / "infrastructure" / "process_identity.py"]
    if any(path.is_symlink() or not path.is_file() for path in required):
        raise ValueError("Expected a complete AgentCaptain source checkout.")
    result = {}
    for name, prefix in (("app.py", []), ("service.py", ["service"]),
                         ("mcp_bridge.py", ["mcp"]), ("terminal_service.py", ["terminal"])):
        text = (f'"""{MARKER}"""\nfrom pathlib import Path\nimport sys\n'
                'sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))\n'
                'from agent_captain.cli import main\n'
                f'if __name__ == "__main__":\n    raise SystemExit(main({prefix!r} + sys.argv[1:]))\n')
        result[name] = text.encode("utf-8")
    result["process_identity.py"] = (
        f'"""{MARKER}"""\nfrom pathlib import Path\nimport runpy\n'
        'if __name__ == "__main__":\n'
        '    runpy.run_path(str(Path(__file__).resolve().parent / "src" / "agent_captain" / '
        '"infrastructure" / "process_identity.py"), run_name="__main__")\n').encode("utf-8")
    result["terminal_broker.cjs"] = (
        f'// {MARKER}\n\x27use strict\x27;\n'
        "const broker = require('./terminal/terminal_broker.cjs');\n"
        "if (require.main === module) broker.main().catch(error => { console.error(error.message); process.exitCode = 1; });\n"
        "module.exports = broker;\n").encode("utf-8")
    # The old running broker ships these bytes over SSH to a machine without
    # this package installed. They must remain complete standalone resources.
    for name in ("remote_pty_bridge.py", "remote_foreground_probe.py"):
        helper = source / "transport" / name
        if helper.is_symlink() or not helper.is_file():
            raise ValueError("A required portable source resource is unavailable.")
        result[name] = helper.read_bytes()
    return result


def prepare(root: Path, *, apply: bool = False) -> dict:
    root = root.expanduser().resolve(strict=True)
    files = compatibility_files(root)
    pending = []
    for name, content in files.items():
        target = root / name
        if target.is_symlink() or (target.exists() and (not target.is_file() or target.read_bytes() != content)):
            raise ValueError("Unknown existing compatibility target; no files were overwritten. Move the old tracked sources into the new layout first.")
        if not target.exists():
            pending.append(name)
    if apply:
        # Exclusive creation also protects against an object appearing after
        # preflight. A partial migration is retained, never recursively removed.
        for name in pending:
            with (root / name).open("xb") as stream:
                stream.write(files[name])
    return {"applied": apply, "files": sorted(files), "created": pending if apply else [],
            "pending": pending if not apply else [], "workers_restarted": False}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--apply", action="store_true", help="Create only the reviewed compatibility entries")
    args = parser.parse_args(argv)
    try:
        print(json.dumps(prepare(args.root, apply=args.apply)))
        return 0
    except (ValueError, OSError):
        print("Migration refused: incomplete checkout or unknown existing target. No existing file was overwritten.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
